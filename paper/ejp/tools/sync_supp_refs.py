"""Write jc_main_refs.tex: the equation, figure, table and section numbers of the
main article (jc_beyond_linear.tex), so that the supplementary material can cite
them with \\mainref{label} instead of numbers typed by hand.

Run this whenever an equation, figure, table or section is added to or removed
from the main text, then rebuild the supplement.  The numbering is obtained by
counting environments in source order, which is how the iopjournal class numbers
them (one counter each, no section prefix)."""
import re, pathlib

HERE = pathlib.Path(__file__).resolve().parents[1]
src = (HERE / 'jc_beyond_linear.tex').read_text()
body = src.split('\\begin{document}', 1)[1].split('\\begin{thebibliography}', 1)[0]
body = re.sub(r'(?<!\\)%.*', '', body)                      # drop comments

refs = {}
for env in ('equation', 'figure', 'table'):
    blocks = re.findall(r'\\begin\{%s\}(.*?)\\end\{%s\}' % (env, env), body, re.S)
    for number, blk in enumerate(blocks, 1):
        labels = re.findall(r'\\label\{([^}]*)\}', blk)
        assert len(labels) == 1, f"{env} {number} must carry exactly one label, found {labels}"
        refs[labels[0]] = number
for number, m in enumerate(re.finditer(r'\\section\{.*?\}\s*\\label\{([^}]*)\}', body, re.S), 1):
    refs[m.group(1)] = number
assert not re.search(r'\\begin\{(align|eqnarray|gather|multline)\*?\}', body), \
    "numbered multi-line environments would break the equation count"

lines = ["% Generated by tools/sync_supp_refs.py from jc_beyond_linear.tex. Do not edit.",
         "\\makeatletter",
         "\\newcommand{\\mainref}[1]{\\@ifundefined{mainref@#1}{\\textbf{??}}{\\@nameuse{mainref@#1}}}"]
lines += [f"\\@namedef{{mainref@{k}}}{{{v}}}" for k, v in refs.items()]
lines += ["\\makeatother", ""]
(HERE / 'jc_main_refs.tex').write_text('\n'.join(lines))

supp = re.sub(r'(?<!\\)%.*', '', (HERE / 'jc_beyond_linear_supp.tex').read_text())   # ignore comments
used = set(re.findall(r'\\mainref\{([^}]*)\}', supp))
missing = used - set(refs)
assert not missing, f"supplement cites labels that the main text does not define: {missing}"
print(f"jc_main_refs.tex: {len(refs)} labels "
      f"({sum(k.startswith('eq:') for k in refs)} equations, {sum(k.startswith('fig:') for k in refs)} figures, "
      f"{sum(k.startswith('tab:') for k in refs)} tables); the supplement uses {len(used)} of them")
